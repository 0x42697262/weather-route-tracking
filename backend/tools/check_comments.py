"""Fail when a Python file holds a comment other than a lint or type directive.

Usage: `python -m tools.check_comments [path ...]`; paths default to the current directory.
"""

import io
import re
import sys
import tokenize
from collections.abc import Iterable, Iterator
from pathlib import Path

ALLOWED_COMMENT = re.compile(r"^#\s*(noqa\b|type:\s*ignore\[|pragma:)")
GENERATED_MIGRATION_HEADER = re.compile(r"^# Generated by Django ")
SKIPPED_DIRECTORIES = frozenset(
    {".venv", ".mypy_cache", ".ruff_cache", ".pytest_cache", "__pycache__"}
)
SHEBANG_PREFIX = "#!"
FAILURE_EXIT_CODE = 1


def comment_violations(source: str) -> Iterator[tuple[int, str]]:
    """Yield the line number and text of every comment that is not allowed."""
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type != tokenize.COMMENT:
            continue
        line_number = token.start[0]
        text = token.string
        is_shebang = line_number == 1 and text.startswith(SHEBANG_PREFIX)
        is_generated = line_number == 1 and GENERATED_MIGRATION_HEADER.match(text)
        if is_shebang or is_generated or ALLOWED_COMMENT.match(text):
            continue
        yield line_number, text


def python_files(roots: Iterable[Path]) -> Iterator[Path]:
    """Yield every Python file under the roots, skipping tool caches and virtualenvs."""
    for root in roots:
        candidates = [root] if root.is_file() else root.rglob("*.py")
        for path in candidates:
            if not SKIPPED_DIRECTORIES.intersection(path.parts):
                yield path


def main(arguments: list[str]) -> int:
    """Print each violation as `path:line: comment` and return the exit code."""
    roots = [Path(argument) for argument in arguments] or [Path()]
    found = False
    for path in python_files(roots):
        for line_number, text in comment_violations(path.read_text(encoding="utf-8")):
            sys.stdout.write(f"{path}:{line_number}: {text}\n")
            found = True
    return FAILURE_EXIT_CODE if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
